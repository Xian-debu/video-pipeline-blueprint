import React from "react";
import { Composition } from "remotion";
import { StoryboardFilm } from "./storyboard/Film";
import { DEMO_STORYBOARD } from "./storyboard/default";
import { DEMO_FILM } from "./storyboard/demo";
import { totalFrames } from "./schema";
import { Transitions } from "./showcase/Transitions";
import { Typesetting } from "./showcase/Typesetting";
import { ThreeCube } from "./showcase/ThreeCube";
import { ThreeStage, THREE_STAGE_FRAMES } from "./showcase/ThreeStage";
import { PlateStage, PLATE_STAGE_FRAMES } from "./showcase/PlateStage";
import { PropStage, PROP_STAGE_FRAMES } from "./showcase/PropStage";
import { ManimOverlay } from "./showcase/ManimOverlay";
import { PresetGallery, PRESET_GALLERY_FRAMES } from "./showcase/PresetGallery";
import { LintAudit } from "./design/lint";
import { LintFixtures } from "./qa/LintFixtures";
import { CONTENT_FILMS } from "./films.generated";

/**
 * Every composition carries the still-lint probe. It renders nothing and does
 * nothing unless scripts/qa/still_lint.mjs passes `{ lint: true, lintFrame }`
 * as input props, so normal renders are unaffected.
 */
const withLint = (C: React.ComponentType<any>): React.FC<any> => {
  const Wrapped = (props: any) => (
    <>
      <C {...props} />
      <LintAudit />
    </>
  );
  return Wrapped;
};

/**
 * 注册的 Composition 分两类：
 *   1) demo —— 引擎自带的分镜模板与能力样张（Storyboard/Showreel/Transitions/…/LintFixtures）；
 *   2) 内容影片 —— 由内容仓 video_project 的 catalog + film.json 生成（见 scripts/films.mjs）。
 *      引擎不静态 import 任何一部影片；没有内容仓时，生成的注册表为空，demo 仍可渲染。
 *
 * 影片默认静音：配乐与旁白由 make.mjs 在成片阶段混入；studio 中可在 props 里手动指向文件。
 */
export const RemotionRoot: React.FC = () => {
  return (
    <>
      <Composition
        id="Storyboard"
        component={withLint(StoryboardFilm)}
        durationInFrames={totalFrames(DEMO_STORYBOARD)}
        fps={DEMO_STORYBOARD.fps}
        width={DEMO_STORYBOARD.width}
        height={DEMO_STORYBOARD.height}
        defaultProps={{ storyboard: DEMO_STORYBOARD }}
      />
      <Composition
        id="Showreel"
        component={withLint(StoryboardFilm)}
        durationInFrames={totalFrames(DEMO_FILM)}
        fps={DEMO_FILM.fps}
        width={DEMO_FILM.width}
        height={DEMO_FILM.height}
        defaultProps={{ storyboard: DEMO_FILM }}
      />
      {CONTENT_FILMS.map((film) => (
        <Composition
          key={film.id}
          id={film.composition}
          component={withLint(film.component)}
          durationInFrames={film.total}
          fps={film.fps}
          width={film.width}
          height={film.height}
          defaultProps={{ music: null, narration: null }}
        />
      ))}
      <Composition id="Transitions" component={withLint(Transitions)} durationInFrames={178} fps={30} width={1920} height={1080} />
      <Composition id="Typesetting" component={withLint(Typesetting)} durationInFrames={240} fps={30} width={1920} height={1080} />
      <Composition id="ThreeCube" component={withLint(ThreeCube)} durationInFrames={120} fps={30} width={1280} height={720} />
      {/* 3D scene layer: procedural lattice -> imported glTF -> transparent composite */}
      <Composition id="ThreeStage" component={withLint(ThreeStage)} durationInFrames={THREE_STAGE_FRAMES} fps={30} width={1920} height={1080} />
      {/* Offline plates: Blender renders them, this composition only consumes them. */}
      <Composition id="PlateStage" component={withLint(PlateStage)} durationInFrames={PLATE_STAGE_FRAMES} fps={30} width={1920} height={1080} defaultProps={{ dir: "showcase" }} />
      {/* SDF/CSG props: generated by scripts/assets/sdf_props.mjs, not sculpted or scanned. */}
      <Composition id="PropStage" component={withLint(PropStage)} durationInFrames={PROP_STAGE_FRAMES} fps={30} width={1920} height={1080} />
      <Composition
        id="Presets"
        component={withLint(PresetGallery)}
        durationInFrames={PRESET_GALLERY_FRAMES}
        fps={30}
        width={1920}
        height={1080}
      />
      <Composition id="ManimOverlay" component={withLint(ManimOverlay)} durationInFrames={60} fps={30} width={1920} height={1080} />
      {/* QA only: deliberately broken layout, never part of a film. */}
      <Composition id="LintFixtures" component={withLint(LintFixtures)} durationInFrames={30} fps={30} width={1920} height={1080} />
    </>
  );
};